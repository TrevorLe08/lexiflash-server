// 1. DailyQuest Model
export interface DailyQuestDocument extends Omit<DailyQuest, 'id'>, Document {
  id: string;
}

const dailyQuestSchema = new Schema<DailyQuestDocument>(
  {
    id: { type: String, required: true, unique: true, index: true },
    userId: { type: String, required: true, index: true },
    date: { type: String, required: true, index: true },
    type: { type: String, required: true },
    title: { type: String, required: true },
    targetCount: { type: Number, required: true },
    currentCount: { type: Number, default: 0 },
    isCompleted: { type: Boolean, default: false },
    actionUrl: { type: String },
    isAutoGenerated: { type: Boolean, default: true },
  },
  {
    timestamps: true,
    toJSON: {
      transform: (_doc, ret: any) => {
        delete ret._id;
        delete ret.__v;
        return ret;
      },
    },
  }
);
dailyQuestSchema.index({ userId: 1, date: 1 });
export const DailyQuestModel = mongoose.model<DailyQuestDocument>(
  'DailyQuest',
  dailyQuestSchema
);

