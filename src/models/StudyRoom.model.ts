// 4. TestHistory Model
export interface TestHistoryDocument extends Omit<TestHistory, 'id'>, Document {
  id: string;
}

const testReviewSchema = new Schema(
  {
    questionId: { type: String, required: true },
    cardId: { type: String, required: true },
    prompt: { type: String, required: true },
    type: { type: String, required: true },
    userAnswer: { type: String, default: '' },
    correctAnswer: { type: String, required: true },
    isCorrect: { type: Boolean, default: false },
  },
  { _id: false }
);

const testHistorySchema = new Schema<TestHistoryDocument>(
  {
    id: { type: String, required: true, unique: true, index: true },
    userId: { type: String, required: true, index: true },
    studySetId: { type: String, required: true, index: true },
    scorePercentage: { type: Number, required: true },
    totalQuestions: { type: Number, required: true },
    correctCount: { type: Number, required: true },
    incorrectCount: { type: Number, required: true },
    timeSpentSeconds: { type: Number, default: 0 },
    questionTypes: { type: [String], default: [] },
    reviews: { type: [testReviewSchema], default: [] },
    correctTerms: { type: [String], default: [] },
    incorrectTerms: { type: [String], default: [] },
  },
  {
    timestamps: true,
    toJSON: {
      transform: (_doc, ret: any) => {
        delete ret._id;
        delete ret.__v;
        return ret;
      },
    },
  }
);
export const TestHistoryModel = mongoose.model<TestHistoryDocument>(
  'TestHistory',
  testHistorySchema
);

